"""Generate the loud-failure base for Forge's cost visitor.

PHASE_06 §6.105. Forge decides what a spell COSTS through
ICostVisitor, which has one visit method per cost type -- eighty of
them at the current pin. Proxic implements the few that ordinary
play needs and must refuse the rest LOUDLY: §6.105 forbids
choosing randomly, choosing the first option, paying automatically
or inventing an answer when an interaction cannot be represented
safely.

Eighty hand-written stubs would rot the moment the Forge pin moves
and nobody would notice which ones had changed. This reads the
interface and emits them, so moving the pin and re-running produces
a diff that IS the change in Forge's cost surface.

    python -I scripts/generate-cost-decision-base.py \\
        <ICostVisitor.java> <output.java>

Same shape as GeneratedControllerBase, which does this for
PlayerController and is why that file says DO NOT hand-edit.
"""
import re
import sys

source, target = sys.argv[1], sys.argv[2]

with open(source, encoding="utf-8") as handle:
    text = handle.read()

# "T visit(CostDiscard cost);" -> CostDiscard
types = re.findall(r"\bT\s+visit\(\s*(\w+)\s+\w+\s*\)\s*;", text)
if not types:
    sys.exit("no visit methods found; has ICostVisitor changed shape?")

seen = list(dict.fromkeys(types))

methods = "\n".join(
    f"""
    @Override
    public PaymentDecision visit({cost} cost) {{
        return loud("{cost}");
    }}"""
    for cost in seen
)

out = f'''package net.barnflix.proxic.worker.game;

import forge.game.card.Card;
import forge.game.cost.*;
import forge.game.player.Player;
import forge.game.spellability.SpellAbility;

/**
 * Every cost Forge can ask about, refused loudly by default.
 *
 * GENERATED by scripts/generate-cost-decision-base.py from Forge's
 * ICostVisitor at the pinned commit. DO NOT hand-edit: regenerate
 * if the pin moves, and the diff is then the change in Forge's cost
 * surface.
 *
 * {len(seen)} cost types at this pin.
 *
 * PHASE_06 §6.105 is the whole design. A cost this adapter cannot
 * represent must not be paid by guessing -- not randomly, not the
 * first option, not automatically. It throws, the match becomes
 * FAILED_RUNTIME, and the exception names the cost type so the next
 * implementation is obvious. Subclasses override the ones they
 * genuinely support.
 */
public abstract class GeneratedCostDecisionBase extends CostDecisionMakerBase {{

    /** Cost types reached this run, in first-touch order. */
    public static final java.util.LinkedHashMap<String, Integer> REACHED_COSTS =
            new java.util.LinkedHashMap<>();

    protected GeneratedCostDecisionBase(
            Player player, boolean effect, SpellAbility ability, Card source) {{
        super(player, effect, ability, source);
    }}

    /**
     * Record and throw.
     *
     * The record survives Forge's own try/catch; the throw is what
     * stops us pretending a cost was paid.
     */
    protected static PaymentDecision loud(String costType) {{
        REACHED_COSTS.merge(costType, 1, Integer::sum);
        System.err.println("[COST REACHED] " + costType);
        throw new UnsupportedOperationException(
                "Proxic does not implement the cost " + costType);
    }}
{methods}
}}
'''

with open(target, "w", encoding="utf-8", newline="\n") as handle:
    handle.write(out)

print(f"generated {len(seen)} cost stubs -> {target}")
