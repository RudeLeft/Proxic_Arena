"""Write docs/testing/MECHANICS_LAB_COVERAGE.md -- PHASE_06 §6.5.

Two inputs, kept apart on purpose:

  Test Deck/Testing Deck/*_SOURCE.txt and *_Coverage.csv
      The corpus, READ-ONLY (§6.4). Which cards, which printings,
      which category, which mechanics. Never copied anywhere.

  docs/testing/mechanics-lab-status.json
      What Proxic has done with each card. Hand-maintained.

The ledger is generated from both, so a status cannot quietly
outlive its card and a card cannot be missing from the ledger.

    python scripts/mechanics-lab-ledger.py           write the ledger
    python scripts/mechanics-lab-ledger.py --check   fail if it is stale

Exit 1 from --check means somebody edited one input without
regenerating. CI runs --check.
"""

from __future__ import annotations

import csv
import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FOLDER = ROOT / "Test Deck" / "Testing Deck"
SOURCE = FOLDER / "Proxic_Arena_Mechanics_Lab_SOURCE.txt"
COVERAGE = FOLDER / "Proxic_Arena_Mechanics_Lab_Coverage.csv"
STATUS = ROOT / "docs" / "testing" / "mechanics-lab-status.json"
LEDGER = ROOT / "docs" / "testing" / "MECHANICS_LAB_COVERAGE.md"

LINE = re.compile(r"^(\d+)\s+(.+?)(?:\s+\[([^:\]]+)(?::([^\]]+))?])?$")

RESULTS = {
    "PASSED", "FAILED", "NOT_YET_TESTED", "BLOCKED_BY_FORGE", "BLOCKED_BY_DECK_PACKAGE",
    "BLOCKED_BY_PROTOCOL", "BLOCKED_BY_UNSUPPORTED_PRESET", "CLASSIFIED",
}
OWNERS = {"P6_REQUIRED", "P7_PRESENTATION", "P8_COVERAGE"}


def front(name: str) -> str:
    return name.split(" // ")[0].strip().lower()


def read_source() -> list[dict]:
    entries = []
    for raw in SOURCE.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("//"):
            continue
        m = LINE.match(line)
        if not m:
            sys.exit(f"unparseable source line: {line!r}")
        entries.append({
            "quantity": int(m.group(1)),
            "name": m.group(2),
            "printing": f"{m.group(3)}:{m.group(4)}" if m.group(3) else "",
        })
    return entries


def read_coverage() -> dict[str, dict]:
    with COVERAGE.open(encoding="utf-8-sig", newline="") as handle:
        return {front(row["card"]): row for row in csv.DictReader(handle)}


def cell(text: str) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


def build() -> str:
    entries = read_source()
    coverage = read_coverage()
    status = json.loads(STATUS.read_text(encoding="utf-8"))
    defaults = status["defaults"]
    cards = status["cards"]

    by_front = {front(e["name"]): e for e in entries}
    unknown = [name for name in cards if front(name) not in by_front]
    if unknown:
        sys.exit(f"status for cards not in the corpus: {unknown}")
    unclassified = [e["name"] for e in entries if front(e["name"]) not in coverage]
    if unclassified:
        sys.exit(f"corpus cards with no CSV row: {unclassified}")

    rows = []
    for e in entries:
        s = {**defaults, **next((v for k, v in cards.items() if front(k) == front(e["name"])), {})}
        if s["result"] not in RESULTS:
            sys.exit(f"{e['name']}: unknown result {s['result']!r}")
        if s["owner"] not in OWNERS:
            sys.exit(f"{e['name']}: unknown owner {s['owner']!r}")
        if s["result"] == "PASSED" and not s.get("evidence"):
            sys.exit(f"{e['name']}: PASSED with no evidence")
        csv_row = coverage[front(e["name"])]
        rows.append({**e, **s, "category": csv_row["category"], "mechanics": csv_row["mechanics"]})

    required = [r for r in rows if r["owner"] == "P6_REQUIRED"]
    results = Counter(r["result"] for r in required)
    owners = Counter(r["owner"] for r in rows)

    out = []
    w = out.append
    w("# Mechanics Lab coverage")
    w("")
    w("<!-- GENERATED by scripts/mechanics-lab-ledger.py from the read-only Mechanics Lab TXT/CSV")
    w("     and docs/testing/mechanics-lab-status.json. Edit the JSON, then regenerate. -->")
    w("")
    w("PHASE_06 §6.5. The implementation-facing ledger for the Mechanics Lab corpus in")
    w("`Test Deck/Testing Deck/`: what each card is there to test (from the CSV), and what")
    w("Proxic has actually done with it (from `mechanics-lab-status.json`).")
    w("")
    w("> **Passing P6-AS does not mean all mechanics in the corpus are supported.** It proves")
    w("> the corpus is read as written, every card resolves to the printing asked for, Forge")
    w("> builds it, its art maps, and a real game starts with it. Whether any one card PLAYS")
    w("> correctly is the per-card result below, and most of those are not yet tested.")
    w("")
    w("## The whole corpus (Layer A, P6-AS)")
    w("")
    total = sum(e["quantity"] for e in entries)
    w(f"- **{len(entries)} entries, {total} cards**, {sum(1 for e in entries if ' // ' in e['name'])} of them multiface.")
    w("- **Forge resolves all of them** to the printing the TXT names, against the pinned Forge")
    w("  (4ec5f1a2). None refused. `MechanicsLabCorpusTest`, which pins that list.")
    w("- **Forge builds a deck** from the corpus and **a real game starts** with it as both")
    w("  libraries. `MechanicsLabCorpusTest`.")
    w("- **Every one of the 275 images** passes the importer's validation, every entry finds its")
    w("  image, and every card finds its art at MATCH time too. `MechanicsLabArtTest` (local only:")
    w("  the images are never committed, AGENTS GIT-001).")
    w("- **The upload route refuses it**, correctly: 390 cards is not Open Format (60-65, §2.45)")
    w("  and its 289 MB of art exceeds the 150 MB package limit. Each import stage is run on its")
    w("  own instead; the refusal itself is asserted.")
    w("- **The TXT and CSV are unchanged** (§6.4): their SHA-256s are pinned in")
    w("  `MechanicsLabCorpusTest`.")
    w("")
    w("## Phase 6 required scenarios (Layer B)")
    w("")
    w(f"{len(required)} cards. " + ", ".join(f"{n} {k}" for k, n in sorted(results.items())) + ".")
    w("")
    w("| Card / Scenario | Source printing | Category | Mechanic / stress case | Tests | Focused test scenario | Forge support | Proxic support | Current result | Evidence | Known issue / blocker | Notes |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for r in required:
        proxic = "Supported" if r["result"] == "PASSED" else "Not proven"
        w("| " + " | ".join(cell(x) for x in [
            r["name"], r["printing"], r["category"], r["mechanics"], r.get("tests", ""),
            r.get("scenario", ""), "Resolves", proxic, r["result"], r.get("evidence", ""),
            r.get("blocker", ""), r.get("notes", ""),
        ]) + " |")
    w("")
    w("## Every card")
    w("")
    w("Phase owners: " + ", ".join(f"{n} {k}" for k, n in sorted(owners.items())) + ". "
      "Unlisted in the status file means `P8_COVERAGE`, exploratory, not yet tested: in the corpus,")
    w("resolved by Forge, and not yet the subject of any Proxic test.")
    w("")
    w("| Card | Printing | Qty | Category | Mechanics (CSV) | Owner | Required | Result |")
    w("|---|---|---|---|---|---|---|---|")
    for r in rows:
        w("| " + " | ".join(cell(str(x)) for x in [
            r["name"], r["printing"], r["quantity"], r["category"], r["mechanics"],
            r["owner"], r["required"], r["result"],
        ]) + " |")
    w("")
    return "\n".join(out)


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        if not LEDGER.exists() or LEDGER.read_text(encoding="utf-8") != text:
            print(f"{LEDGER.relative_to(ROOT)} is stale: run python scripts/mechanics-lab-ledger.py")
            return 1
        print("ledger is current")
        return 0
    LEDGER.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {LEDGER.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
